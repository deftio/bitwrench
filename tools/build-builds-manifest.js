#!/usr/bin/env node
/**
 * Build dist/builds.json — manifest of all distribution files with sizes.
 *
 * Usage: node tools/build-builds-manifest.js
 *
 * Scans dist/ for .js and .css files (skips .map and _sri.txt),
 * computes raw and gzipped byte sizes, and writes the manifest JSON.
 */

import { readdirSync, statSync, readFileSync, writeFileSync, existsSync } from 'fs';
import { gzipSync } from 'zlib';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const distDir = join(__dirname, '..', 'dist');
const outputPath = join(distDir, 'builds.json');

// Read package.json for version
const pkg = JSON.parse(readFileSync(join(__dirname, '..', 'package.json'), 'utf8'));

// Read SRI hashes if available (generated by tools/generate-sri.js)
const sriPath = join(distDir, 'sri.json');
let sriHashes = {};
if (existsSync(sriPath)) {
  const sriData = JSON.parse(readFileSync(sriPath, 'utf8'));
  sriHashes = sriData.files || {};
}

// Get all distributable files (skip .map, builds.json, sri.json)
const allFiles = readdirSync(distDir).filter(f => {
  if (f === 'builds.json' || f === 'sri.json') return false;
  if (f.endsWith('.map')) return false;
  if (f.endsWith('_sri.txt')) return false;
  return f.endsWith('.js') || f.endsWith('.cjs') || f.endsWith('.css');
});

// Determine which files have source maps
const mapFiles = new Set(readdirSync(distDir).filter(f => f.endsWith('.map')));

const files = allFiles.map(file => {
  const filePath = join(distDir, file);
  const raw = statSync(filePath).size;
  // The size that can fail a release is the one tools/release.js gates on:
  // the shipped .gz artifact, written at level 9. Recompressing at zlib's
  // default (level 6) gave a number ~140 bytes larger, so the downloads page
  // and the changelog told different stories about the same file. Prefer the
  // artifact; fall back to level 9, never the default.
  const gzPath = filePath + '.gz';
  const gzipped = existsSync(gzPath)
    ? statSync(gzPath).size
    : gzipSync(readFileSync(filePath), { level: 9 }).length;

  // Determine format
  let format = 'Unknown';
  if (file.endsWith('.css')) {
    format = 'CSS';
  } else if (file.includes('.es5.')) {
    format = 'ES5 (UMD)';
  } else if (file.includes('.esm.')) {
    format = 'ESM';
  } else if (file.endsWith('.cjs')) {
    // CJS builds use a bare .cjs extension: package.json sets
    // "type": "module", so a .js file would be parsed as ESM and break
    // require(). The extension is what forces CommonJS parsing.
    format = 'CJS';
  } else if (file.includes('.umd.')) {
    format = 'UMD';
  }

  const ver = '2.x';

  // Minified?
  const minified = file.includes('.min.');

  // Source map?
  const sourceMap = mapFiles.has(file + '.map');

  // Identify component: core library vs addons vs lean vs bccl vs bwserve vs debug
  let component = 'core';
  if (file.startsWith('bitwrench-code-edit')) component = 'code-edit';
  else if (file.startsWith('bitwrench-debug')) component = 'debug';
  else if (file.startsWith('bitwrench-lean')) component = 'lean';
  else if (file.startsWith('bitwrench-bccl')) component = 'bccl';
  else if (file.startsWith('bitwrench-verify')) component = 'verify';
  else if (file.startsWith('bwserve')) component = 'bwserve';

  // bitwrench-debug.js and bitwrench-verify.js have no format suffix -- both
  // are UMD. Without this they ship as format "Unknown", and without the
  // component case above verify lands under `core` -- which is precisely the
  // opposite of the release's claim that it is NOT in the core bundle.
  if (format === 'Unknown' && (component === 'debug' || component === 'verify')) format = 'UMD';

  const entry = { file, format, ver, component, minified, raw, gzipped, sourceMap };
  if (sriHashes[file]) {
    entry.integrity = sriHashes[file];
  }
  return entry;
});

// Sort: by format, then non-min before min
files.sort((a, b) => {
  if (a.format !== b.format) return a.format.localeCompare(b.format);
  if (a.minified !== b.minified) return a.minified ? 1 : -1;
  return a.file.localeCompare(b.file);
});

const manifest = {
  version: pkg.version,
  buildDate: new Date().toISOString().split('T')[0],
  files
};

writeFileSync(outputPath, JSON.stringify(manifest, null, 2), 'utf8');
console.log('Generated dist/builds.json (' + files.length + ' files)');
