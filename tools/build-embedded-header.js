#!/usr/bin/env node
/**
 * Generate embedded_c/bitwrench_embedded.h (and _lean.h): the minified
 * bitwrench bundle as a flash-resident byte array.
 *
 * Why: a board with no filesystem (no LittleFS/SPIFFS partition, or an
 * AVR/RP2040 sketch that does not want one) still has to answer
 * GET /bitwrench.js. Without this, every embedded project either mounts a
 * filesystem it did not want or points the browser at a CDN, which breaks the
 * "works offline, on an isolated network" claim that embedded users are here
 * for.
 *
 * What is embedded is the **gzipped** bundle, served with
 * `Content-Encoding: gzip`. Raw would be ~169 KB of flash and ~1 MB of C
 * source; gzipped is ~46 KB and every browser that can run bitwrench can
 * decompress it. Both headers carry the version and the SRI hash of the file
 * they were generated from, so a stale header is visible.
 *
 * Usage: node tools/build-embedded-header.js
 */

import { readFileSync, writeFileSync, statSync } from 'fs';
import { createHash } from 'crypto';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

const TARGETS = [
  {
    src: 'dist/bitwrench.umd.min.js.gz',
    out: 'embedded_c/bitwrench_embedded.h',
    guard: 'BITWRENCH_EMBEDDED_H',
    symbol: 'bitwrench_js_gz',
    label: 'full build (every make*() component)'
  },
  {
    src: 'dist/bitwrench-lean.umd.min.js.gz',
    out: 'embedded_c/bitwrench_embedded_lean.h',
    guard: 'BITWRENCH_EMBEDDED_LEAN_H',
    symbol: 'bitwrench_lean_js_gz',
    label: 'lean build (no BCCL component factories)'
  }
];

function hexArray(buf, perLine = 16) {
  const lines = [];
  for (let i = 0; i < buf.length; i += perLine) {
    const row = [];
    for (let j = i; j < Math.min(i + perLine, buf.length); j++) {
      row.push('0x' + buf[j].toString(16).padStart(2, '0'));
    }
    lines.push('  ' + row.join(', ') + (i + perLine < buf.length ? ',' : ''));
  }
  return lines.join('\n');
}

let generated = 0;

for (const t of TARGETS) {
  const srcPath = join(root, t.src);
  let buf;
  try {
    buf = readFileSync(srcPath);
  } catch (e) {
    console.error('✗ ' + t.src + ' not found — run `npm run build` first');
    process.exitCode = 1;
    continue;
  }

  const sri = 'sha384-' + createHash('sha384').update(buf).digest('base64');
  const kb = (buf.length / 1024).toFixed(1);

  const header = `/*
 * bitwrench_embedded.h — ${t.label}, gzipped, as a flash-resident array.
 *
 * GENERATED by tools/build-embedded-header.js. Do not edit.
 *   bitwrench v${pkg.version}
 *   source:   ${t.src}
 *   size:     ${buf.length} bytes (${kb} KB) gzipped
 *   SRI:      ${sri}
 *
 * Serve it with Content-Encoding: gzip. The browser decompresses; nothing on
 * the device has to. No filesystem, no network, no CDN.
 *
 *   #include <bitwrench_embedded.h>
 *
 *   server.on("/bitwrench.js", HTTP_GET, [](){
 *       server.sendHeader("Content-Encoding", "gzip");
 *       server.sendHeader("Cache-Control", "max-age=31536000, immutable");
 *       server.send_P(200, "application/javascript",
 *                     (const char *)${t.symbol}, ${t.symbol}_len);
 *   });
 *
 * Then the page is one script tag and one mount:
 *
 *   <script src="/bitwrench.js"></script>
 *   <script>bw.mount("#app", { t: "h1", c: "ESP32 is alive" });</script>
 *
 * PROGMEM is a no-op on 32-bit targets (ESP32, RP2040, STM32) and matters on
 * AVR, where it keeps the array out of RAM. ${buf.length} bytes of flash is
 * more than an ATmega328 has, so AVR boards should serve from a filesystem or
 * use a proxy; ESP32/RP2040 class parts have room.
 */

#ifndef ${t.guard}
#define ${t.guard}

#ifdef __AVR__
#include <avr/pgmspace.h>
#else
#ifndef PROGMEM
#define PROGMEM
#endif
#endif

#define BITWRENCH_EMBEDDED_VERSION "${pkg.version}"
#define ${t.symbol.toUpperCase()}_LEN ${buf.length}

static const unsigned char ${t.symbol}[] PROGMEM = {
${hexArray(buf)}
};

static const unsigned int ${t.symbol}_len = ${buf.length};

#endif /* ${t.guard} */
`;

  writeFileSync(join(root, t.out), header);
  const outKB = (statSync(join(root, t.out)).size / 1024).toFixed(0);
  console.log('Generated ' + t.out + ' (' + kb + ' KB payload, ' + outKB + ' KB of C)');
  generated++;
}

// ─── Size table for embedded_c/README.md ─────────────────────────────────────
// Embedded developers choose on flash and RAM numbers, and we already compute
// them in builds.json. Generated between markers so it cannot go stale.

const readmePath = join(root, 'embedded_c', 'README.md');
const START = '<!-- sizes:start -->';
const END = '<!-- sizes:end -->';

try {
  const readme = readFileSync(readmePath, 'utf8');
  if (readme.indexOf(START) !== -1 && readme.indexOf(END) !== -1) {
    const rows = [];
    const want = [
      ['bitwrench.umd.min.js', 'full build, every component'],
      ['bitwrench-lean.umd.min.js', 'no BCCL component factories'],
      ['bitwrench.es5.min.js', 'ES5, for older engines']
    ];
    for (const [file, note] of want) {
      let raw, gz;
      try {
        raw = statSync(join(root, 'dist', file)).size;
        gz = statSync(join(root, 'dist', file + '.gz')).size;
      } catch (e) { continue; }
      rows.push('| `' + file + '` | ' + (raw / 1024).toFixed(0) + ' KB | ' +
        (gz / 1024).toFixed(1) + ' KB | ' + note + ' |');
    }

    const headerSizes = TARGETS.map((t) => {
      try {
        return '| `' + t.out.replace('embedded_c/', '') + '` | ' +
          (statSync(join(root, t.out)).size / 1024).toFixed(0) + ' KB of C | ' +
          (statSync(join(root, t.src)).size / 1024).toFixed(1) + ' KB in flash | ' +
          t.label + ' |';
      } catch (e) { return null; }
    }).filter(Boolean);

    const block = [
      START,
      '',
      '_Generated by `tools/build-embedded-header.js` for v' + pkg.version + '. Do not edit._',
      '',
      'What the browser downloads (serve the `.gz` with `Content-Encoding: gzip`):',
      '',
      '| File | On disk | Gzipped | Notes |',
      '|------|---------|---------|-------|',
      ...rows,
      '',
      'What it costs the device, if you embed it in flash instead of a filesystem:',
      '',
      '| Header | Source size | Flash cost | Contents |',
      '|--------|-------------|------------|----------|',
      ...headerSizes,
      '',
      'RAM cost is the send buffer only: `BW_BUF_SIZE` (512 B by default) plus',
      '`BW_TACO_BUF_SIZE` (256 B), both stack-allocated per call, plus',
      '`BW_MAX_CLIENTS` x `sizeof(int)` for the client registry. The payload',
      'itself stays in flash and is streamed, never copied into RAM.',
      '',
      END
    ].join('\n');

    const next = readme.slice(0, readme.indexOf(START)) + block +
      readme.slice(readme.indexOf(END) + END.length);
    if (next !== readme) {
      writeFileSync(readmePath, next);
      console.log('Updated embedded_c/README.md size table');
    }
  }
} catch (e) { /* README optional */ }

if (generated === 0) process.exitCode = 1;
